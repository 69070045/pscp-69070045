text = input().lower()
if text.count("a") > 0:
    print(f"a : {text.count("a")}")
if text.count("e") > 0:
    print(f"e : {text.count("e")}")
if text.count("i") > 0:
    print(f"i : {text.count("i")}")
if text.count("o") > 0:
    print(f"o : {text.count("o")}")
if text.count("u") > 0:
    print(f"u : {text.count("u")}")
